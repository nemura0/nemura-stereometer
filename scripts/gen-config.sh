#!/usr/bin/env bash
# Generates Sources/Core/include/nmr/product_config.h from config/product.env.
#   scripts/gen-config.sh          write the header
#   scripts/gen-config.sh --check  fail if the committed header is stale (CI)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=../config/product.env
source "$ROOT/config/product.env"
OUT="$ROOT/Sources/Core/include/nmr/product_config.h"

fourcc() { # 'Stmt' -> 0x53746d74
  local s="$1"
  if [[ ${#s} -ne 4 ]]; then
    echo "error: four-char code '$s' must be 4 characters" >&2
    exit 1
  fi
  printf '0x%02x%02x%02x%02x' "'${s:0:1}" "'${s:1:1}" "'${s:2:1}" "'${s:3:1}"
}

IFS='.' read -r V_MAJOR V_MINOR V_PATCH <<<"$NMR_VERSION"
if (( ${#NMR_SHM_PREFIX} + 6 > 31 )); then
  echo "error: NMR_SHM_PREFIX too long for macOS shm names" >&2
  exit 1
fi

generate() {
  cat <<EOF
// Generated by scripts/gen-config.sh from config/product.env. Do not edit by hand.
#pragma once

#define NMR_PRODUCT_NAME "${NMR_PRODUCT_NAME}"
#define NMR_PRODUCT_SHORT "${NMR_PRODUCT_SHORT}"
#define NMR_VENDOR "${NMR_VENDOR}"
#define NMR_COPYRIGHT "${NMR_COPYRIGHT}"
#define NMR_URL "${NMR_URL}"
#define NMR_DESCRIPTION "${NMR_DESCRIPTION}"

#define NMR_VERSION "${NMR_VERSION}"
#define NMR_VERSION_MAJOR ${V_MAJOR}
#define NMR_VERSION_MINOR ${V_MINOR}
#define NMR_VERSION_PATCH ${V_PATCH}
#define NMR_BUILD ${NMR_BUILD}

#define NMR_APP_BUNDLE_ID "${NMR_APP_BUNDLE_ID}"
#define NMR_PLUGIN_BUNDLE_ID "${NMR_PLUGIN_BUNDLE_ID}"
#define NMR_CLAP_ID "${NMR_CLAP_ID}"
#define NMR_AU_TYPE_CODE $(fourcc "$NMR_AU_TYPE")
#define NMR_AU_SUBTYPE_CODE $(fourcc "$NMR_AU_SUBTYPE")
#define NMR_AU_MANUFACTURER_CODE $(fourcc "$NMR_AU_MANUFACTURER")

#define NMR_SHM_PREFIX "${NMR_SHM_PREFIX}"
#define NMR_OBJC_PREFIX_TOKEN ${NMR_OBJC_PREFIX}
#define NMR_SUPPORT_SUBDIR "${NMR_SUPPORT_SUBDIR}"
#define NMR_LOG_SUBSYSTEM "${NMR_LOG_SUBSYSTEM}"
EOF
}

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -u "$OUT" <(generate); then
    echo "error: $OUT is stale; run scripts/gen-config.sh" >&2
    exit 1
  fi
  echo "product_config.h is up to date"
else
  mkdir -p "$(dirname "$OUT")"
  generate >"$OUT"
  echo "wrote ${OUT#"$ROOT"/}"
fi
